export function buildInitialRoadmapWeeks() {
  return rawRoadmapSeed.map((w, idx) => ({
    _id: `week_${w.weekNo}_${idx}`,
    weekNo: w.weekNo,
    startDate: w.startDate,
    endDate: w.endDate,
    phase: w.phase,
    title: w.title,
    topics: w.topics.map((t, tIdx) => ({
      _id: `topic_${w.weekNo}_${tIdx}`,
      text: t,
      done: false,
      doneAt: null,
    })),
    status: 'upcoming',
    shiftedByDays: 0,
  }));
}
